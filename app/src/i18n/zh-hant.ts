/**
 * 領域詞組覆寫（字符轉換後執行）。
 * 歷法用字（曆法 / 日曆 / 公曆 / 佛曆 / 農曆）與一情多義詞在此校正。
 */
const PHRASES: Array<[string, string]> = [
  ['幹支', '干支'],
  ['納採', '納采'],
  ['鐘表', '鐘錶'],
  ['復制', '複製'],
  ['历法', '曆法'],
  ['日历', '日曆'],
  ['公历', '公曆'],
  ['佛历', '佛曆'],
  ['农历', '農曆'],
  // 一情多義校正（法務與 Cookie 文案）
  ['開啓', '開啟'],
  ['答復', '答覆'],
  ['聯系', '聯繫'],
];

/** 簡體中文 → 繁體中文（字符轉換 + 詞組覆寫） */
export function s2t(text: string): string {
  let out = '';
  for (const ch of text) out += CHARS[ch] ?? ch;
  for (const [from, to] of PHRASES) out = out.split(from).join(to);
  return out;
}

/** 繁體語言包（由 zh 派生，key 一一對應） */
export const zhHant: Record<MsgKey, string> = {} as Record<MsgKey, string>;
for (const [k, v] of Object.entries(zh) as Array<[MsgKey, string]>) {
  zhHant[k] = s2t(v);
}
